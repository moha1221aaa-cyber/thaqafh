def dl(i):
    p = os.path.join(TMP, "%d.mp3" % i)
    if not os.path.exists(p) or os.path.getsize(p) < 1000:
        try:
            req = urllib.request.Request("https://assets.mixkit.co/active_storage/sfx/%d/%d-preview.mp3" % (i, i), headers={"User-Agent": "Mozilla/5.0"})
            open(p, "wb").write(urllib.request.urlopen(req, timeout=25).read())
        except Exception as e:
            print("skip", i, e); return None
    return p
def peak(path):
    r = subprocess.run(["ffmpeg", "-i", path, "-af", "volumedetect", "-f", "null", "-"], capture_output=True, text=True).stderr
    m = re.search(r"max_volume: (-?[\d.]+) dB", r); return float(m.group(1)) if m else 0.0
